#!/usr/bin/env python3
"""Build data/words.js from the official Globasa word list.

The app loads this file with a plain <script> tag so it also works from
file:// without a server or a build step.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "word-list.csv"
TARGET = ROOT / "data" / "words.js"

CLASS_LABELS = {
    "b": "n/v",
    "b.oj": "v.tr",
    "b.oj.ru": "v.tr echo",
    "b.nenoj": "v.intr",
    "b.oro": "v.ambi",
    "b.oro.jotay": "v.ambi motion",
    "b.oro.hisi": "v.ambi feeling",
    "b.lin": "v.cop",
    "b.lin.oj": "v.cop tr",
    "b.sah": "v.aux",
    "f.sah": "v.aux",
    "n": "n",
    "s": "adj",
    "t": "adj/adv",
    "m": "adv",
    "pn": "pron",
    "su pn": "poss pron",
    "su n": "prop n",
    "su s": "poss adj",
    "su t": "prop adj/adv",
    "d": "det",
    "il": "interj",
    "l": "conj",
    "num": "num",
    "par": "particle",
    "p": "adp",
    "lp": "prep",
    "xp": "postp",
    "lfik": "pfx",
    "xfik": "sfx",
    "fik": "afx",
}


def class_label(code: str) -> str:
    code = code.strip()
    if not code:
        return "other"

    labels: list[str] = []
    for part in code.split(";"):
        part = part.strip()
        if not part:
            continue
        base = part
        suffix = ""
        if base.startswith("tabel:"):
            base = base[len("tabel:"):].strip()
            suffix = " correlative"
        if base.startswith("p jm"):
            label = "prep phrase"
        elif base.startswith("f jm"):
            label = "verb phrase"
        elif base.startswith("n jm"):
            label = "noun phrase"
        elif base.startswith("t jm"):
            label = "adj/adv phrase"
        elif base.startswith("l jm"):
            label = "conj phrase"
        elif base.startswith("m jm"):
            label = "adv phrase"
        elif base.startswith("s jm"):
            label = "adj phrase"
        elif base.endswith(" xfik"):
            label = class_label(base[: -len(" xfik")]) + " + sfx"
        elif base.endswith(".p"):
            label = class_label(base[:-2]) + " + prep"
        elif "nenhuru genu" in base:
            label = "phrase"
        else:
            label = CLASS_LABELS.get(base, base)
        label += suffix
        if label not in labels:
            labels.append(label)
    return "; ".join(labels) if labels else "other"


def main() -> None:
    with SOURCE.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)

    entries = []
    classes: dict[str, int] = {}
    categories: dict[str, int] = {}
    for row in rows:
        word = (row.get("Word") or "").strip()
        if not word:
            continue
        code = (row.get("WordClass") or "").strip()
        label = class_label(code)
        gloss = " ".join((row.get("TranslationEng") or "").split())
        category = (row.get("Category") or "").strip() or "other"
        entries.append([word, label, gloss, category])
        classes[label] = classes.get(label, 0) + 1
        categories[category] = categories.get(category, 0) + 1

    entries.sort(key=lambda item: item[0].lower())
    payload = {
        "count": len(entries),
        "classes": dict(sorted(classes.items(), key=lambda kv: (-kv[1], kv[0]))),
        "categories": dict(sorted(categories.items(), key=lambda kv: (-kv[1], kv[0]))),
        "entries": entries,
    }
    js = (
        "/* Generated by tools/build_words.py from word-list.csv. Do not edit. */\n"
        "window.GLOBASA_WORDS = "
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    TARGET.write_text(js, encoding="utf-8")
    print(f"Wrote {TARGET} with {len(entries)} entries ({TARGET.stat().st_size:,} bytes)")
    print("Classes:", ", ".join(f"{k}={v}" for k, v in list(payload["classes"].items())[:12]))


if __name__ == "__main__":
    main()
